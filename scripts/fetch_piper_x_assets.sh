#!/usr/bin/env bash
# Materialise the pinned Piper X assets outside every git repository.
#
#   bash scripts/fetch_piper_x_assets.sh
#   JCHENG_ASSET_ROOT=/path/to/assets bash scripts/fetch_piper_x_assets.sh
#
# The script fetches only MIT/LGPL sources that were audited on 2026-11-26.
# It never fetches agx_arm_sim or piper_isaac_sim: those repositories have no
# LICENSE file, even though agx_arm_sim's README says "MIT License".
#
# Output: ${JCHENG_ASSET_ROOT:-$HOME/.local/share/jcheng/assets}/piper_x
set -euo pipefail

ASSET_BASE="${JCHENG_ASSET_ROOT:-$HOME/.local/share/jcheng/assets}"
DEST="${ASSET_BASE}/piper_x"

URDF_REPO="https://github.com/agilexrobotics/agx_arm_urdf"
URDF_SHA="680fa925cd00db7e2628563d2edc5540963045de"
ROS_REPO="https://github.com/agilexrobotics/agx_arm_ros"
ROS_SHA="747d0722074d4cebc095d8d44f3ef68d2023ba6f"
SDK_REPO="https://github.com/agilexrobotics/piper_sdk"
SDK_SHA="b847e5393a7ce6ff8508d713eca7bdd3a42421b4"
PY_REPO="https://github.com/agilexrobotics/pyAgxArm"
PY_SHA="d90e234ba8e408cfa964b38aa9120b3131fc9f85"

need() {
    command -v "$1" >/dev/null 2>&1 || {
        printf 'missing required command: %s\n' "$1" >&2
        exit 1
    }
}
need git
need sha256sum
need python3

WORK="$(mktemp -d "${TMPDIR:-/tmp}/jcheng-piper-x.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

echo "== asset root: $DEST"
mkdir -p "$DEST"

checkout_pinned() {
    local repo="$1" sha="$2" dir="$3"
    git clone --filter=blob:none --no-checkout "$repo" "$dir" >/dev/null
    git -C "$dir" fetch --depth 1 origin "$sha" >/dev/null
    git -C "$dir" checkout --detach "$sha" >/dev/null
    local got
    got="$(git -C "$dir" rev-parse HEAD)"
    if [[ "$got" != "$sha" ]]; then
        printf 'commit mismatch for %s: expected %s, got %s\n' "$repo" "$sha" "$got" >&2
        exit 1
    fi
    printf '%s @ %s\n' "$repo" "$sha"
}

echo "== urdf and gripper (MIT)"
git clone --filter=blob:none --no-checkout "$URDF_REPO" "$WORK/urdf" >/dev/null
git -C "$WORK/urdf" sparse-checkout init --cone
git -C "$WORK/urdf" sparse-checkout set piper_x agx_gripper
git -C "$WORK/urdf" fetch --depth 1 origin "$URDF_SHA" >/dev/null
git -C "$WORK/urdf" checkout --detach "$URDF_SHA" >/dev/null
[[ "$(git -C "$WORK/urdf" rev-parse HEAD)" == "$URDF_SHA" ]] || {
    echo "urdf commit mismatch" >&2
    exit 1
}
printf '%s @ %s\n' "$URDF_REPO" "$URDF_SHA"

echo "== ROS 2 driver and MoveIt configs (MIT)"
checkout_pinned "$ROS_REPO" "$ROS_SHA" "$WORK/ros"

echo "== piper_sdk (MIT, legacy)"
checkout_pinned "$SDK_REPO" "$SDK_SHA" "$WORK/sdk"

echo "== pyAgxArm (LGPL-3.0)"
checkout_pinned "$PY_REPO" "$PY_SHA" "$WORK/py"

rm -rf \
    "$DEST/agx_arm_urdf-680fa925" \
    "$DEST/agx_arm_ros-747d0722" \
    "$DEST/piper_sdk-b847e539" \
    "$DEST/pyAgxArm-d90e234b"
mkdir -p \
    "$DEST/agx_arm_urdf-680fa925" \
    "$DEST/agx_arm_ros-747d0722" \
    "$DEST/piper_sdk-b847e539" \
    "$DEST/pyAgxArm-d90e234b"

cp -a "$WORK/urdf/LICENSE" "$WORK/urdf/README.md" "$WORK/urdf/README_EN.md" \
    "$WORK/urdf/piper_x" "$WORK/urdf/agx_gripper" \
    "$DEST/agx_arm_urdf-680fa925/"
cp -a "$WORK/ros/LICENSE" "$WORK/ros/README.md" "$WORK/ros/README_EN.md" \
    "$WORK/ros/src/agx_arm_ctrl" "$WORK/ros/src/agx_arm_description" \
    "$WORK/ros/src/agx_arm_moveit" "$WORK/ros/src/agx_arm_msgs" "$WORK/ros/docs" \
    "$DEST/agx_arm_ros-747d0722/"
mkdir -p "$DEST/agx_arm_ros-747d0722/src"
mv "$DEST/agx_arm_ros-747d0722/agx_arm_ctrl" \
    "$DEST/agx_arm_ros-747d0722/agx_arm_description" \
    "$DEST/agx_arm_ros-747d0722/agx_arm_moveit" \
    "$DEST/agx_arm_ros-747d0722/agx_arm_msgs" \
    "$DEST/agx_arm_ros-747d0722/src/"

cp -a "$WORK/sdk/." "$DEST/piper_sdk-b847e539/"
rm -rf "$DEST/piper_sdk-b847e539/.git"
cp -a "$WORK/py/." "$DEST/pyAgxArm-d90e234b/"
rm -rf "$DEST/pyAgxArm-d90e234b/.git"

if [[ ! -f "$DEST/README.md" ]]; then
    cat >"$DEST/README.md" <<'EOF'
# Piper X asset bundle

Generated by `jcheng-simulation/scripts/fetch_piper_x_assets.sh`. Binary assets
are intentionally kept outside every git repository. Run `sha256sum -c
SHA256SUMS` before using them. See `PROVENANCE.json` for the pinned commits and
licences; see `jcheng-simulation/docs/robots/piper_x/` for the manifest.
EOF
fi

echo "== ament prefix shim (agx_arm_description -> agx_arm_urdf)"
# The upstream xacro includes $(find agx_arm_description)/agx_arm_urdf/... and
# its meshes use package://agx_arm_description/... . The agx_arm_ros package
# ships agx_arm_urdf empty; point it at the fetched URDF repository so the
# jcheng-simulation engine can resolve both from one prefix.
PREFIX="$DEST/prefix"
mkdir -p "$PREFIX/share/ament_index/resource_index/packages" \
         "$PREFIX/share/agx_arm_description"
touch "$PREFIX/share/ament_index/resource_index/packages/agx_arm_description"
ln -sfn "$DEST/agx_arm_urdf-680fa925" \
    "$PREFIX/share/agx_arm_description/agx_arm_urdf"

echo "== checksums"
cd "$DEST"
find . -type f \
    ! -path './SHA256SUMS' \
    ! -path './PROVENANCE.json' \
    ! -path './README.md' \
    -print0 | sort -z | xargs -0 sha256sum >SHA256SUMS

python3 -I - "$DEST" <<'PY'
import json
import sys
from pathlib import Path

dest = Path(sys.argv[1])
excluded = {"SHA256SUMS", "PROVENANCE.json", "README.md"}
files = [
    p for p in dest.rglob("*")
    if p.is_file() and p.relative_to(dest).as_posix() not in excluded
]
payload = sum(p.stat().st_size for p in files)
data = {
    "schema_version": 1,
    "bundle": "piper_x",
    "materialized_at": "2026-11-26",
    "method": "git clone/fetch at pinned commits; binaries outside git",
    "default_root": "~/.local/share/jcheng/assets/piper_x",
    "payload_files": len(files),
    "payload_bytes": payload,
    "sources": [
        {"id": "agx_arm_urdf", "commit": "680fa925cd00db7e2628563d2edc5540963045de", "license": "MIT"},
        {"id": "agx_arm_ros", "commit": "747d0722074d4cebc095d8d44f3ef68d2023ba6f", "license": "MIT"},
        {"id": "piper_sdk", "commit": "b847e5393a7ce6ff8508d713eca7bdd3a42421b4", "license": "MIT"},
        {"id": "pyAgxArm", "commit": "d90e234ba8e408cfa964b38aa9120b3131fc9f85", "license": "LGPL-3.0"},
    ],
    "unfetched": ["agx_arm_sim (no LICENSE)", "piper_isaac_sim (no LICENSE)"],
}
(dest / "PROVENANCE.json").write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
PY

printf 'materialized %s\n' "$DEST"
printf 'files: %s\n' "$(wc -l <SHA256SUMS)"
printf 'payload bytes: %s\n' "$(find . -type f ! -path './SHA256SUMS' ! -path './PROVENANCE.json' ! -path './README.md' -printf '%s\n' | awk '{s+=$1} END {print s+0}')"
printf 'verify: cd %s && sha256sum -c SHA256SUMS\n' "$DEST"
